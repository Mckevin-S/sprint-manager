-- Utilisateurs
CREATE TABLE app_user (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(160) NOT NULL,
    full_name     VARCHAR(80)  NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE UNIQUE INDEX ux_app_user_email ON app_user (LOWER(email));

-- Projets et membres
CREATE TABLE project (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_key       VARCHAR(6)   NOT NULL UNIQUE,
    name              VARCHAR(80)  NOT NULL,
    description       VARCHAR(500),
    wip_limit         INTEGER      NOT NULL,
    next_issue_number INTEGER      NOT NULL,
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    version           BIGINT       NOT NULL
);

CREATE TABLE membership (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT      NOT NULL REFERENCES project (id) ON DELETE CASCADE,
    user_id    BIGINT      NOT NULL REFERENCES app_user (id),
    role       VARCHAR(20) NOT NULL,
    joined_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ux_membership UNIQUE (project_id, user_id)
);
CREATE INDEX ix_membership_user ON membership (user_id);

-- Sprints
CREATE TABLE sprint (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id       BIGINT       NOT NULL REFERENCES project (id) ON DELETE CASCADE,
    name             VARCHAR(60)  NOT NULL,
    goal             VARCHAR(300),
    status           VARCHAR(10)  NOT NULL,
    start_date       DATE,
    end_date         DATE,
    started_at       TIMESTAMP WITH TIME ZONE,
    closed_at        TIMESTAMP WITH TIME ZONE,
    committed_points INTEGER,
    completed_points INTEGER,
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_sprint_project_status ON sprint (project_id, status);
-- Un seul sprint actif par projet, garanti aussi par la base
CREATE UNIQUE INDEX ux_sprint_one_active ON sprint (project_id) WHERE status = 'ACTIVE';

-- Tickets
CREATE TABLE issue (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id   BIGINT       NOT NULL REFERENCES project (id) ON DELETE CASCADE,
    number       INTEGER      NOT NULL,
    type         VARCHAR(10)  NOT NULL,
    title        VARCHAR(160) NOT NULL,
    description  TEXT,
    status       VARCHAR(15)  NOT NULL,
    priority     VARCHAR(10)  NOT NULL,
    story_points INTEGER,
    assignee_id  BIGINT REFERENCES app_user (id),
    reporter_id  BIGINT       NOT NULL REFERENCES app_user (id),
    sprint_id    BIGINT REFERENCES sprint (id) ON DELETE SET NULL,
    backlog_rank BIGINT       NOT NULL,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    resolved_at  TIMESTAMP WITH TIME ZONE,
    version      BIGINT       NOT NULL,
    CONSTRAINT ux_issue_number UNIQUE (project_id, number)
);
CREATE INDEX ix_issue_project_sprint ON issue (project_id, sprint_id);
CREATE INDEX ix_issue_assignee_status ON issue (assignee_id, status);

CREATE TABLE issue_comment (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    issue_id   BIGINT        NOT NULL REFERENCES issue (id) ON DELETE CASCADE,
    author_id  BIGINT        NOT NULL REFERENCES app_user (id),
    body       VARCHAR(4000) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_issue_comment_issue ON issue_comment (issue_id);

-- Journal d'activité : historique des tickets et source du burndown
CREATE TABLE activity_event (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id      BIGINT       NOT NULL REFERENCES project (id) ON DELETE CASCADE,
    issue_id        BIGINT,
    issue_key       VARCHAR(20),
    sprint_id       BIGINT,
    actor_id        BIGINT       NOT NULL REFERENCES app_user (id),
    type            VARCHAR(30)  NOT NULL,
    summary         VARCHAR(300) NOT NULL,
    remaining_delta INTEGER,
    occurred_at     TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_activity_project_time ON activity_event (project_id, occurred_at DESC);
CREATE INDEX ix_activity_issue ON activity_event (issue_id);
CREATE INDEX ix_activity_sprint ON activity_event (sprint_id);
